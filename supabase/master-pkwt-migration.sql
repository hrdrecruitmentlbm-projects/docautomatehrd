-- 1.1 Tabel pkwt_scan_roots (Daftar root folder Google Drive yang dipindai)
create table if not exists pkwt_scan_roots (
  id bigint generated by default as identity primary key,
  label text not null default '',
  folder_id text not null,
  aktif boolean not null default true,
  mulai_dari_bulan text,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create unique index if not exists pkwt_scan_roots_folder_id_idx
  on pkwt_scan_roots (folder_id);

-- 1.2 Tabel pkwt_scan_exclusions (Pola teks/file yang diabaikan saat pemindaian)
create table if not exists pkwt_scan_exclusions (
  id bigint generated by default as identity primary key,
  pola text not null unique,
  created_at timestamp with time zone not null default now()
);

insert into pkwt_scan_exclusions (pola)
values
  ('Paklaring'),
  ('SLIP EMAIL'),
  ('Template'),
  ('KOP'),
  ('ttd')
on conflict (pola) do nothing;

-- 1.3 Tabel pkwt_source (Hasil pemindaian arsip Google Drive)
create table if not exists pkwt_source (
  id bigint generated by default as identity primary key,
  file_id text not null unique,
  nomor_surat text,
  nama_asli text,
  nama_key text,
  kode_perusahaan text,
  bulan_folder text,
  tanggal_mulai text,
  tanggal_berakhir text,
  jangka_bulan integer,
  perlu_dicek boolean not null default false,
  alasan_cek text,
  manual_override boolean not null default false,
  drive_modified_time timestamp with time zone,
  url text,
  scanned_at timestamp with time zone not null default now()
);

create index if not exists pkwt_source_nama_key_idx on pkwt_source (nama_key);
create index if not exists pkwt_source_tanggal_berakhir_idx on pkwt_source (tanggal_berakhir);
create index if not exists pkwt_source_bulan_folder_idx on pkwt_source (bulan_folder);
create index if not exists pkwt_source_perlu_dicek_idx on pkwt_source (perlu_dicek);
create index if not exists pkwt_source_file_id_idx on pkwt_source (file_id);
create index if not exists pkwt_source_dedup_key_idx on pkwt_source (nama_key, tanggal_mulai) where nama_key is not null;
create index if not exists pkwt_source_manual_override_idx on pkwt_source (manual_override);
create index if not exists pkwt_source_kode_perusahaan_idx on pkwt_source (kode_perusahaan);

