-- Tabel untuk menyimpan status tunda (snooze) notifikasi kontrak PKWT per karyawan & tanggal berakhir
create table if not exists pkwt_notif_state (
  id bigint generated by default as identity primary key,
  nama_key text not null,
  tanggal_berakhir text not null,
  snoozed_until timestamp with time zone not null,
  user_email text,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

-- Indeks unik untuk upsert berdasarkan kombinasi (nama_key, tanggal_berakhir)
create unique index if not exists pkwt_notif_state_key_end_idx
  on pkwt_notif_state (nama_key, tanggal_berakhir);

-- Indeks untuk query status tunda yang masih aktif (snoozed_until > now())
create index if not exists pkwt_notif_state_snoozed_until_idx
  on pkwt_notif_state (snoozed_until);

