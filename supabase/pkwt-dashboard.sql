-- ============ 1. Tabel pkwt_scan_roots ============
-- Menyimpan daftar folder root Google Drive yang dipindai untuk arsip PKWT
create table if not exists pkwt_scan_roots (
  id bigint generated by default as identity primary key,
  label text not null default '',
  folder_id text not null,
  aktif boolean not null default true,
  mulai_dari_bulan text,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

-- Indeks unik pada folder_id agar tidak terjadi duplikasi folder scan
create unique index if not exists pkwt_scan_roots_folder_id_idx on pkwt_scan_roots (folder_id);

-- ============ 2. Tabel pkwt_scan_exclusions ============
-- Menyimpan pola kata/teks file yang harus diabaikan saat pemindaian
create table if not exists pkwt_scan_exclusions (
  id bigint generated by default as identity primary key,
  pola text not null unique,
  created_at timestamp with time zone not null default now()
);

-- Seed pola pengecualian bawaan
insert into pkwt_scan_exclusions (pola)
values
  ('Paklaring'),
  ('SLIP EMAIL'),
  ('Template'),
  ('KOP'),
  ('ttd')
on conflict (pola) do nothing;

-- ============ 3. Tabel pkwt_source ============
-- Menyimpan metadata dokumen PKWT yang dipindai dari Google Drive
create table if not exists pkwt_source (
  id bigint generated by default as identity primary key,
  file_id text not null unique,
  nomor_surat text,
  nama_asli text,
  nama_key text,
  kode_perusahaan text,
  bulan_folder text,
  tanggal_mulai text,
  tanggal_berakhir text,
  jangka_bulan integer,
  perlu_dicek boolean not null default false,
  alasan_cek text,
  manual_override boolean not null default false,
  drive_modified_time timestamp with time zone,
  url text,
  scanned_at timestamp with time zone not null default now()
);

-- Indeks penelusuran cepat
create index if not exists pkwt_source_nama_key_idx on pkwt_source (nama_key);
create index if not exists pkwt_source_tanggal_berakhir_idx on pkwt_source (tanggal_berakhir);
create index if not exists pkwt_source_bulan_folder_idx on pkwt_source (bulan_folder);
create index if not exists pkwt_source_perlu_dicek_idx on pkwt_source (perlu_dicek);

-- ============ 4. Reload Schema Cache PostgREST ============
notify pgrst, 'reload schema';
